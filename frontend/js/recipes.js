const URGENCY_WEIGHT = { urgent: 3, warning: 2, fresh: 1 };
const matches = (item, keywords) => keywords.some((k) => item.name.toLowerCase().includes(k));

/**
 * Локальный генератор. Возвращает null, если нет ни одного подходящего рецепта.
 * Результат всегда помечается как локальный демо-сценарий — это не ответ нейросети.
 */
export function generateLocalRecipe(items) {
  const pool = sortByUrgency(items);
  let best = null;
  for (const r of CATALOG) {
    const used = new Map();
    let score = 0;
    for (const group of r.needs) {
      const hit = pool.find((it) => matches(it, group) && !used.has(it.id));
      if (hit) { used.set(hit.id, hit); score += URGENCY_WEIGHT[hit.status]; }
    }
    if (used.size >= 2 && (!best || score > best.score)) best = { r, used: [...used.values()], score };
  }
  if (!best) return null;

  const rescued = best.used.filter((i) => i.status !== 'fresh');
  const rescuedBase = rescued.length ? rescued : best.used;
  return {
    title: best.r.title,
    emoji: best.r.emoji,
    cooking_time_min: best.r.time,
    difficulty: best.r.difficulty,
    used_ingredients: best.used.map((i) => i.name),
    fridge_item_ids: best.used.map((i) => i.id),
    rescued_count: rescued.length,
    money_saved_tenge: rescuedBase.reduce((s, i) => s + i.price_tenge, 0),
    co2_prevented_kg: co2For(rescuedBase.reduce((s, i) => s + i.weight_kg, 0)),
    steps: best.r.steps,
    eco_tip: best.r.tip,
    source: 'local',
  };
}
